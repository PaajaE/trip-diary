import {
  mapPreviewSvg,
  MAP_PREVIEW_BACKGROUND,
  type MapPreview,
} from '@trip-diary/core/public-journey'
import { lazy, Suspense, useCallback, useEffect, useRef, useState } from 'react'
import { ReaderMapAttribution } from '@/features/journeys/ui/ReaderMapAttribution'
import type { PublicJourneyMapProps } from '@/features/public-journey/ui/PublicJourneyMap'

// MapLibre (~265 KB) is only requested once the map is about to be seen.
const loadMap = () => import('@/features/public-journey/ui/PublicJourneyMap')
const LazyMap = lazy(loadMap)

/** Reserved-height placeholder, identical to the map box (no layout shift). */
export function MapSkeleton() {
  return (
    <div
      aria-hidden="true"
      className="h-[22rem] w-full animate-pulse rounded-lg border border-border bg-surface sm:h-[28rem]"
    />
  )
}

/**
 * True once the element is within ~200 px of the viewport AND the browser is
 * idle. Without IntersectionObserver (old browsers, jsdom) it is true at once.
 */
function useNearViewport<T extends Element>() {
  const ref = useRef<T>(null)
  const [near, setNear] = useState(
    () => typeof IntersectionObserver === 'undefined',
  )
  useEffect(() => {
    const element = ref.current
    if (near || element === null) return undefined
    let cancelIdle: (() => void) | undefined
    let cancelLoad: (() => void) | undefined
    const observer = new IntersectionObserver(
      (entries) => {
        if (!entries.some((entry) => entry.isIntersecting)) return
        observer.disconnect()
        // Download (no execution) the 265 KB chunk now; it is mounted below.
        void loadMap().catch(() => undefined)
        // After the window load event (hero image included), so the 265 KB
        // map chunk never competes with the LCP image, then when idle.
        const afterIdle = () => {
          if (typeof window.requestIdleCallback === 'function') {
            const handle = window.requestIdleCallback(
              () => {
                setNear(true)
              },
              { timeout: 1500 },
            )
            cancelIdle = () => {
              window.cancelIdleCallback(handle)
            }
            return
          }
          const handle = window.setTimeout(() => {
            setNear(true)
          }, 0)
          cancelIdle = () => {
            window.clearTimeout(handle)
          }
        }
        if (document.readyState === 'complete') {
          afterIdle()
        } else {
          window.addEventListener('load', afterIdle, { once: true })
          cancelLoad = () => {
            window.removeEventListener('load', afterIdle)
          }
        }
      },
      { rootMargin: '200px' },
    )
    observer.observe(element)
    return () => {
      observer.disconnect()
      cancelIdle?.()
      cancelLoad?.()
    }
  }, [near])
  return { near, ref }
}

const BOX =
  'relative h-[22rem] w-full overflow-hidden rounded-lg border border-border sm:h-[28rem]'

interface PublicMapSectionProps extends PublicJourneyMapProps {
  /**
   * Static route preview shown until the map has rendered; it must be the
   * same one the prerendered page paints (buildMapPreview), then the map
   * fades in over it. Without it the box is the pulsing skeleton.
   */
  preview?: MapPreview | null | undefined
}

export function PublicMapSection({ preview, ...props }: PublicMapSectionProps) {
  const { near, ref } = useNearViewport<HTMLDivElement>()
  const [ready, setReady] = useState(false)
  const markReady = useCallback(() => {
    setReady(true)
  }, [])
  useEffect(() => {
    if (!near || ready) return undefined
    // Never leave the preview up if the map signals nothing (tile errors).
    const timer = window.setTimeout(markReady, 8000)
    return () => {
      window.clearTimeout(timer)
    }
  }, [near, ready, markReady])
  const hasPreview = preview !== null && preview !== undefined
  return (
    <section>
      <div
        className={`${BOX} ${hasPreview ? '' : 'bg-surface'} ${
          hasPreview || ready ? '' : 'animate-pulse'
        }`}
        ref={ref}
        style={hasPreview ? { background: MAP_PREVIEW_BACKGROUND } : undefined}
      >
        {hasPreview ? (
          <div
            aria-hidden="true"
            className={`absolute inset-0 transition-opacity duration-300 ${
              ready ? 'opacity-0' : ''
            }`}
            // Numbers only (no user text): generated by mapPreviewSvg().
            dangerouslySetInnerHTML={{ __html: mapPreviewSvg(preview) }}
          />
        ) : null}
        {near ? (
          <Suspense fallback={null}>
            <div
              className={`absolute inset-0 transition-opacity duration-300 ${
                ready ? 'opacity-100' : 'opacity-0'
              }`}
            >
              <LazyMap
                {...props}
                className="h-full w-full"
                onReady={markReady}
              />
            </div>
          </Suspense>
        ) : null}
      </div>
      <ReaderMapAttribution />
    </section>
  )
}
